        "Возможности:\n\n"
        "💱 Конвертация валют\n"
        "Переводит одну валюту в другую по актуальному курсу.\n\n"
        "📈 Актуальные курсы валют\n"
        "Показывает текущие курсы USD, EUR и RUB относительно TJS.\n\n"
        "📜 История операций\n"
        "Сохраняет все ваши конвертации с датой и временем.\n\n"
        "Как пользоваться?\n\n"
        "1️⃣ Нажмите «💱 Конвертация валют».\n\n"
        "2️⃣ Введите сумму и валюту.\n\n"
